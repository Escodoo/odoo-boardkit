export function alpha2ToNumeric(code) {
    if (!code) {
        return null;
    }
    return ALPHA2_TO_NUMERIC[String(code).toUpperCase()] || null;
}

export function numericToAlpha2(numericId) {
    if (numericId === undefined || numericId === null) {
        return null;
    }
    const raw = String(numericId);
    const padded = raw.padStart(3, "0");
    return NUMERIC_TO_ALPHA2[padded] || NUMERIC_TO_ALPHA2[raw] || null;
}
